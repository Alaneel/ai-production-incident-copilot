@app.middleware("http")
async def observe_request(request: Request, call_next):
    if request.url.path in {"/health", "/metrics"}:
        return await call_next(request)
    started = time.perf_counter()
    request_id = request_correlation_id(request.headers.get("x-request-id") or request.headers.get("x-trace-id"))
    request.state.request_id = request_id
    status = "ok"
    tracer = trace.get_tracer("incident-lab")
    parent_context = extract(dict(request.headers))
    with tracer.start_as_current_span(
        f"{request.method} {request.url.path}",
        context=parent_context,
        kind=trace.SpanKind.SERVER,
    ) as span:
        span.set_attribute("service.name", SERVICE_NAME)
        span.set_attribute("incident.fault", state.active_mode())
        span.set_attribute("http.request.id", request_id)
        try:
            response = await call_next(request)
            if response.status_code >= 500:
                status = "error"
            return response
        except Exception as error:
            status = "error"
            span.record_exception(error)
            raise
        finally:
            duration = time.perf_counter() - started
            REQUESTS.labels(SERVICE_NAME, request.url.path, status).inc()
            LATENCY.labels(SERVICE_NAME, request.url.path).observe(duration)
            logger.info(
                "request completed",
                extra={
                    "fields": {
                        "request_id": request_id,
                        "path": request.url.path,
                        "status": status,
                        "duration_ms": round(duration * 1000, 2),
                        "fault": state.active_mode(),
                    }
                },
            )


