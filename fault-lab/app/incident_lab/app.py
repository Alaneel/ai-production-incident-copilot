def configure_tracing() -> None:
    endpoint = os.getenv("OTEL_EXPORTER_OTLP_ENDPOINT", "").rstrip("/")
    if not endpoint:
        return
    provider = TracerProvider(
        resource=Resource.create(
            {
                "service.name": SERVICE_NAME,
                "deployment.environment.name": "fault-lab",
                "service.version": RELEASE_REVISION,
            }
        )
    )
    provider.add_span_processor(
        BatchSpanProcessor(OTLPSpanExporter(endpoint=f"{endpoint}/v1/traces"))
    )
    trace.set_tracer_provider(provider)


@asynccontextmanager
async def lifespan(_: FastAPI):
    global http_client, postgres_pool
    configure_tracing()
    http_client = httpx.AsyncClient(timeout=httpx.Timeout(4.0))
    log_shipper = asyncio.create_task(ship_logs())
    DB_POOL_MAX.labels(SERVICE_NAME).set(50)
    DB_POOL_ACTIVE.labels(SERVICE_NAME).set(8)
    DEPLOYMENT.labels(SERVICE_NAME, RELEASE_REVISION).set(1)
    try:
        backend = os.getenv("INCIDENT_LAB_DB_POOL_BACKEND", "simulation")
        if backend not in {"simulation", "postgres"}:
            raise ValueError("Unsupported lab database backend")
        if backend == "postgres":
            if not os.getenv("FAULT_INJECTION_TOKEN") or FAULT_TOKEN == "local-fault-token":
                raise ValueError("Real PostgreSQL pool experiments require an explicit non-default fault token")
            def observe(active, maximum):
                DB_POOL_ACTIVE.labels(SERVICE_NAME).set(active)
                DB_POOL_MAX.labels(SERVICE_NAME).set(maximum)
            postgres_pool = LocalPostgresPool(observe=observe)
            await postgres_pool.open(os.environ["INCIDENT_LAB_POSTGRES_URL"])
        yield
    finally:
        if postgres_pool is not None:
            await postgres_pool.close()
            postgres_pool = None
        log_shipper.cancel()
        with suppress(asyncio.CancelledError):
            await log_shipper
        await http_client.aclose()


async def push_log_batch(client: httpx.AsyncClient, endpoint: str, values: list[list[str]]) -> bool:
    """Retry the same identities before consuming later records; not exactly-once."""
    payload = {"streams": [{"stream": {"service": SERVICE_NAME, "environment": "fault-lab"}, "values": values}]}
    for attempt in range(LOG_PUSH_ATTEMPTS):
        try:
            response = await client.post(endpoint, json=payload)
            response.raise_for_status()
        except httpx.HTTPStatusError as error:
            if error.response.status_code != 429 and error.response.status_code < 500:
                LOG_DROPPED.labels(SERVICE_NAME, "rejected").inc(len(values))
                return False
        except httpx.RequestError:
            pass
        else:
            LOG_DELIVERED.labels(SERVICE_NAME).inc(len(values))
            return True
        if attempt + 1 < LOG_PUSH_ATTEMPTS:
            LOG_RETRIES.labels(SERVICE_NAME).inc()
            await asyncio.sleep(min(0.5 * 2 ** attempt, 4.0))
    LOG_DROPPED.labels(SERVICE_NAME, "retry_exhausted").inc(len(values))
    return False


async def ship_logs() -> None:
    endpoint = os.getenv("LOKI_PUSH_URL", "")
    values: list[list[str]] = []
    try:
        while True:
            await asyncio.sleep(0.5)
            if not endpoint or http_client is None:
                continue
            while len(values) < LOG_BATCH_LIMIT:
                try:
                    timestamp, line = log_queue.get_nowait()
                except queue.Empty:
                    break
                values.append([timestamp, line])
            if values:
                await push_log_batch(http_client, endpoint, values)
                values = []
    finally:
        # Explicit accounting, not a durable shutdown flush. No recursive log
        # messages, and cancellation remains prompt even during a Loki outage.
        lost = len(values)
        while True:
            try:
                log_queue.get_nowait()
                lost += 1
            except queue.Empty:
                break
        if lost:
            LOG_DROPPED.labels(SERVICE_NAME, "shutdown").inc(lost)


