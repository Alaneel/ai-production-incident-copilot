@app.get("/v1/work")
@app.post("/v1/work")
async def work(request: Request) -> JSONResponse:
    request_id = getattr(request.state, "request_id", None) or request_correlation_id(None)
    mode = state.active_mode()
    if postgres_pool is not None:
        try:
            await postgres_pool.query()
        except PoolExhausted:
            logger.error("database connection acquisition timed out", extra={"fields": {
                "request_id": request_id, "active": postgres_pool.active, "max": postgres_pool.size,
                "fault": mode, "db_pool_backend": "postgres"}})
            return JSONResponse({"error": "database connection acquisition timed out"}, status_code=503)
        except PostgresError:
            return JSONResponse({"error": "local database query failed"}, status_code=503)
    if mode == "db_pool_exhaustion" and postgres_pool is None:
        DB_POOL_ACTIVE.labels(SERVICE_NAME).set(50)
        await asyncio.sleep(0.35 + state.intensity * 0.65)
        logger.error(
            "database connection acquisition timed out",
            extra={
                "fields": {
                    "request_id": request_id,
                    "pool": "ledger-primary",
                    "active": 50,
                    "max": 50,
                    "fault": mode,
                }
            },
        )
        return JSONResponse(
            {"error": "database connection acquisition timed out"},
            status_code=503,
        )
    if mode == "downstream_timeout":
        await asyncio.sleep(1.5 + state.intensity * 2.0)
        logger.error(
            "downstream request timed out",
            extra={"fields": {"request_id": request_id, "fault": mode}},
        )
        return JSONResponse({"error": "downstream timeout"}, status_code=504)
    if mode == "cpu_spike":
        CPU_LOAD.labels(SERVICE_NAME).set(state.intensity)
        deadline = time.perf_counter() + 0.1 + state.intensity * 0.25
        accumulator = 1
        while time.perf_counter() < deadline:
            accumulator = (accumulator * 17 + 11) % 1_000_003
    if mode == "memory_leak":
        allocation = bytes(1024 * 1024)
        maximum_chunks = max(1, int(128 * state.intensity))
        if len(state.retained_memory) < maximum_chunks:
            state.retained_memory.append(allocation)
        MEMORY_BYTES.labels(SERVICE_NAME).set(
            sum(len(chunk) for chunk in state.retained_memory)
        )
    if mode == "deployment_regression" and random.random() < state.intensity:
        logger.error(
            "release regression: invalid ledger response shape",
            extra={
                "fields": {
                    "request_id": request_id,
                    "revision": RELEASE_REVISION,
                    "fault": mode,
                }
            },
        )
        return JSONResponse({"error": "invalid ledger response"}, status_code=500)
    if mode == "kafka_consumer_lag":
        KAFKA_LAG.labels(SERVICE_NAME).inc(250 * state.intensity)
    if mode == "cache_penetration":
        CACHE_MISSES.labels(SERVICE_NAME).inc()
        CACHE_MISS_RATE.labels(SERVICE_NAME).set(state.intensity * 10)
        if postgres_pool is None:
            DB_POOL_ACTIVE.labels(SERVICE_NAME).set(
                min(45, 8 + len(state.retained_memory) + int(30 * state.intensity))
            )
    if mode == "retry_storm":
        attempts = max(2, int(6 * state.intensity))
        RETRY_RATE.labels(SERVICE_NAME).set(float(attempts))
        for _ in range(attempts):
            RETRIES.labels(SERVICE_NAME).inc()
            await call_downstream(request_id, tolerate_failure=True)

    downstream = await call_downstream(request_id, tolerate_failure=False)
    context = trace.get_current_span().get_span_context()
    return JSONResponse(
        {
            "service": SERVICE_NAME,
            "status": "ok",
            "fault": mode,
            "trace_id": format(context.trace_id, "032x") if context.is_valid else None,
            "request_id": request_id,
            "downstream": downstream,
        }
    )


async def call_downstream(request_id: str, *, tolerate_failure: bool) -> dict | None:
    if not DOWNSTREAM_URL or http_client is None:
        return None
    headers = {"x-request-id": request_id}
    tracer = trace.get_tracer("incident-lab")
    try:
        with tracer.start_as_current_span("call downstream", kind=trace.SpanKind.CLIENT) as span:
            inject(headers)
            span.set_attribute("server.address", DOWNSTREAM_URL)
            response = await http_client.post(
                f"{DOWNSTREAM_URL}/v1/work",
                headers=headers,
            )
            span.set_attribute("http.response.status_code", response.status_code)
        response.raise_for_status()
        return response.json()
    except (httpx.TimeoutException, httpx.HTTPStatusError) as error:
        if tolerate_failure:
            return {"status": "retryable", "error": type(error).__name__}
        logger.error(
            "downstream dependency failed",
            extra={
                "fields": {
                    "request_id": request_id,
                    "downstream": DOWNSTREAM_URL,
                    "fault": state.active_mode(),
                }
            },
        )
        return {"status": "failed", "error": type(error).__name__}


def authorize_fault(token: str | None) -> None:
    if not token or not secrets.compare_digest(token, FAULT_TOKEN):
        raise HTTPException(status_code=401, detail="invalid fault injection token")


@app.get("/admin/pool")
async def inspect_pool(x_fault_token: str | None = Header(default=None)) -> dict:
    """Read-only lab inspection; no connection details or credentials."""
    authorize_fault(x_fault_token)
    pool = postgres_pool
    return {"backend": "postgres" if pool is not None else "simulation",
            "active": pool.active if pool is not None else None,
            "maximum": pool.size if pool is not None else None,
            "backend_pids": [connection.info.backend_pid for connection in pool.connections] if pool is not None else []}


@app.post("/admin/fault")
async def inject_fault(
    fault: FaultRequest,
    x_fault_token: str | None = Header(default=None),
) -> dict:
    authorize_fault(x_fault_token)
    if postgres_pool is not None:
        await postgres_pool.clear_fault()
        if fault.mode == "db_pool_exhaustion":
            try:
                await postgres_pool.exhaust(fault.duration_seconds)
            except PoolExhausted:
                state.clear()
                raise HTTPException(status_code=409, detail="Lab connections are busy; no pool fault started") from None
    state.clear()
    state.mode = fault.mode
    state.intensity = fault.intensity
    state.expires_at = datetime.now(UTC) + timedelta(seconds=fault.duration_seconds)
    state.expires_monotonic = time.monotonic() + fault.duration_seconds
    state.incident_id = fault.incident_id
    if fault.mode != "none":
        FAULT_ACTIVE.labels(SERVICE_NAME, fault.mode).set(1)
    logger.warning(
        "fault injected",
        extra={
            "fields": {
                "fault": fault.mode,
                "incident_id": fault.incident_id,
                "duration_seconds": fault.duration_seconds,
                "intensity": fault.intensity,
            }
        },
    )
    return {
        "accepted": True,
        "service": SERVICE_NAME,
        "fault": fault.mode,
        "expires_at": state.expires_at.isoformat(),
    }


@app.delete("/admin/fault")
async def clear_fault(x_fault_token: str | None = Header(default=None)) -> dict:
    authorize_fault(x_fault_token)
    previous = state.active_mode()
    if postgres_pool is not None:
        await postgres_pool.clear_fault()
    state.clear()
    logger.warning("fault cleared", extra={"fields": {"fault": previous}})
    return {"cleared": True, "service": SERVICE_NAME, "previous_fault": previous}
