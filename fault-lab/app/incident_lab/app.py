class FaultRequest(BaseModel):
    mode: FaultMode
    intensity: float = Field(default=0.8, ge=0.1, le=1.0)
    duration_seconds: int = Field(default=180, ge=10, le=900)
    incident_id: str = Field(default="manual", min_length=2, max_length=80)


@dataclass
class FaultState:
    mode: FaultMode = "none"
    intensity: float = 0
    expires_at: datetime | None = None
    expires_monotonic: float | None = None
    incident_id: str | None = None
    retained_memory: list[bytes] = field(default_factory=list)

    def active_mode(self) -> FaultMode:
        # Wall time is display metadata only: clock corrections must not
        # shorten or extend the bounded fault injection interval.
        if self.expires_monotonic is not None and time.monotonic() >= self.expires_monotonic:
            self.clear()
        return self.mode

    def clear(self) -> None:
        if self.mode != "none":
            FAULT_ACTIVE.labels(SERVICE_NAME, self.mode).set(0)
        self.mode = "none"
        self.intensity = 0
        self.expires_at = None
        self.expires_monotonic = None
        self.incident_id = None
        self.retained_memory.clear()
        if postgres_pool is None:
            DB_POOL_ACTIVE.labels(SERVICE_NAME).set(8)
        else:
            postgres_pool.report()
        CPU_LOAD.labels(SERVICE_NAME).set(0)
        MEMORY_BYTES.labels(SERVICE_NAME).set(0)
        CACHE_MISS_RATE.labels(SERVICE_NAME).set(0)
        RETRY_RATE.labels(SERVICE_NAME).set(0)
        KAFKA_LAG.labels(SERVICE_NAME).set(0)


