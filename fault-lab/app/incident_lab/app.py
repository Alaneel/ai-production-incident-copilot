def request_correlation_id(raw: str | None) -> str:
    if isinstance(raw, str) and re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._:-]{0,79}", raw):
        return raw
    return secrets.token_hex(8)


class JsonFormatter(logging.Formatter):
    def format(self, record: logging.LogRecord) -> str:
        payload = {
            "timestamp": datetime.now(UTC).isoformat(),
            "level": record.levelname.lower(),
            "service": SERVICE_NAME,
            "message": record.getMessage(),
        }
        fields = getattr(record, "fields", {})
        if isinstance(fields, dict):
            reserved = {"timestamp", "level", "service", "message", "trace_id", "span_id"}
            payload.update({key: value for key, value in fields.items() if key not in reserved})
        context = trace.get_current_span().get_span_context()
        if context.is_valid:
            payload["trace_id"] = format(context.trace_id, "032x")
            payload["span_id"] = format(context.span_id, "016x")
        return json.dumps(payload, separators=(",", ":"))


class LokiQueueHandler(logging.Handler):
    def emit(self, record: logging.LogRecord) -> None:
        try:
            line = self.format(record)
            if len(line.encode("utf-8")) > LOG_LINE_LIMIT:
                LOG_DROPPED.labels(SERVICE_NAME, "oversize").inc()
                return
            log_queue.put_nowait((str(time.time_ns()), line))
        except queue.Full:
            LOG_DROPPED.labels(SERVICE_NAME, "queue_full").inc()
        except Exception:
            self.handleError(record)


